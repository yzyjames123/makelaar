/**
 * Get all unique cities from seed data
 */
export function getSeedCities(): string[] {
  return [...new Set(seedProperties.map((p) => p.city))].sort();
}

/**
 * Filter seed properties by criteria
 */
export function filterSeedProperties(options: {
  city?: string | null;
  minPrice?: number | null;
  maxPrice?: number | null;
  minBedrooms?: number | null;
}): ScrapedProperty[] {
  let filtered = [...seedProperties];

  if (options.city) {
    filtered = filtered.filter((p) => p.city.toLowerCase() === options.city!.toLowerCase());
  }
  if (options.minPrice) {
    filtered = filtered.filter((p) => p.price >= options.minPrice!);
  }
  if (options.maxPrice) {
    filtered = filtered.filter((p) => p.price <= options.maxPrice!);
  }
  if (options.minBedrooms) {
    filtered = filtered.filter((p) => (p.bedrooms || 0) >= options.minBedrooms!);
  }

  return filtered;
}
